# Compiles the shared indexed shaders to Direct3D 11 DXBC (shader model 5.0)
# and writes them as static byte arrays to src/rg_gui_d3d11_shaders.h, the
# header rg_gui_d3d11.h includes. Needs fxc (Windows SDK) on PATH.
#
#   powershell -ExecutionPolicy Bypass -File shaders\build_d3d11.ps1 [-Out <header>]
#
# build.bat shaders_d3d11 runs it; build.bat test_d3d11 regenerates into out\
# and fails if the committed header differs from the sources.
param([string]$Out = "")
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $Out) { $Out = Join-Path $root 'src\rg_gui_d3d11_shaders.h' }
$shaders = Join-Path $root 'shaders'
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("rg_gui_dxbc_" + $PID)
New-Item -ItemType Directory -Force $tmp | Out-Null
$variants = @(
	@{ Name = 'rg_gui_d3d11_indexed_vs'; Profile = 'vs_5_0'; Source = 'rg_gui_indexed.vert.hlsl'; Defines = @('/DRG_D3D11') },
	@{ Name = 'rg_gui_d3d11_indexed_ps'; Profile = 'ps_5_0'; Source = 'rg_gui_indexed.frag.hlsl'; Defines = @('/DRG_D3D11') },
	@{ Name = 'rg_gui_d3d11_indexed_ps_coverage'; Profile = 'ps_5_0'; Source = 'rg_gui_indexed.frag.hlsl'; Defines = @('/DRG_D3D11', '/DRG_GUI_ATLAS_COVERAGE') }
)
$text = New-Object System.Text.StringBuilder
[void]$text.Append("// rg_gui_d3d11_shaders - DXBC for rg_gui_d3d11.h. Generated by shaders/build_d3d11.ps1`n")
[void]$text.Append("// (build.bat shaders_d3d11) from rg_gui_indexed.vert.hlsl and rg_gui_indexed.frag.hlsl;`n")
[void]$text.Append("// do not edit. fxc /T vs_5_0 or ps_5_0 /E main /O3 /DRG_D3D11 [/DRG_GUI_ATLAS_COVERAGE].`n`n")
[void]$text.Append("#ifndef RG_GUI_D3D11_SHADERS_H`n#define RG_GUI_D3D11_SHADERS_H`n")
try {
	foreach ($v in $variants) {
		$obj = Join-Path $tmp ($v.Name + '.dxbc')
		$fxcArgs = @('/nologo', '/T', $v.Profile, '/E', 'main', '/O3', '/WX') + $v.Defines + @('/Fo', $obj, (Join-Path $shaders $v.Source))
		& fxc @fxcArgs | Out-Null
		if ($LASTEXITCODE -ne 0) { throw "fxc failed for $($v.Name)" }
		$bytes = [System.IO.File]::ReadAllBytes($obj)
		[void]$text.Append("`nstatic const unsigned char $($v.Name)[$($bytes.Length)] = {")
		for ($i = 0; $i -lt $bytes.Length; $i++) {
			if ($i % 16 -eq 0) { [void]$text.Append("`n`t") } else { [void]$text.Append(' ') }
			[void]$text.Append(('0x{0:x2},' -f $bytes[$i]))
		}
		[void]$text.Append("`n};`n")
	}
	[void]$text.Append("`n#endif // RG_GUI_D3D11_SHADERS_H`n")
	[System.IO.File]::WriteAllText($Out, $text.ToString(), (New-Object System.Text.UTF8Encoding($false)))
	Write-Host "Wrote $Out"
}
finally {
	Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
}
